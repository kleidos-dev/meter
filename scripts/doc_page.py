"""What the generators of the pages of ``docs/`` share: the header, the tables, the check.

``gen_http_api_doc.py``, ``gen_cli_doc.py`` and ``gen_python_api_doc.py`` each
write one page from the code it describes; a test of the host package holds
each page to its generator. No third-party module.
"""

from __future__ import annotations

import argparse
import inspect
import sys
from collections.abc import Callable, Iterable, Sequence
from pathlib import Path


def header(generator: str, source: str) -> list[str]:
    """The comments a generated page opens with, and the blank line after them.

    :param generator: The script's name, in ``scripts/``.
    :param source: What it writes the page from.
    :returns: The lines.
    """
    return [
        # REUSE-IgnoreStart (the page's own header, not this file's)
        "<!-- SPDX-FileCopyrightText: 2026 José M. Requena Plens -->",
        "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
        # REUSE-IgnoreEnd
        f"<!-- Generated by scripts/{generator} from {source}: do not edit. -->",
        "",
    ]


def cell(text: str) -> str:
    """Escape *text*'s bars, so that it is one cell of a table.

    :param text: The cell.
    :returns: It escaped.
    """
    return text.replace("|", "\\|")


def table(heads: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    """Write a table, a line a row.

    :param heads: The columns' titles.
    :param rows: The rows' cells.
    :returns: The lines.
    """
    lines = ["| " + " | ".join(heads) + " |", "|" + "---|" * len(heads)]
    return lines + ["| " + " | ".join(cell(text) for text in row) + " |" for row in rows]


def code(words: Iterable[str]) -> str:
    """Write *words* each as code, or a dash for none.

    :param words: The words.
    :returns: Them, comma-separated.
    """
    return ", ".join(f"`{word}`" for word in words) or "–"


def anchor(title: str) -> str:
    """The fragment of a heading, as GitHub makes it.

    :param title: The heading's text, its backticks left out or not.
    :returns: The fragment, without its ``#``.
    """
    kept = [char for char in title.lower() if char.isalnum() or char in "-_ "]
    return "".join(kept).replace(" ", "-")


def run(
    argv: list[str] | None,
    page: Callable[[], str],
    out: Path,
    description: str,
    holds: str,
) -> int:
    """Run a generator's command line: write its page, or check it.

    :param argv: The arguments, ``sys.argv[1:]`` when None.
    :param page: Writes the page's text.
    :param out: Where the page is.
    :param description: What the generator does, for ``--help``.
    :param holds: What the page is written from, for a stale page's message.
    :returns: 0, or 1 when ``--check`` finds the page is not the generator's.
    """
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument("--check", action="store_true", help="fail when the page is stale")
    parser.add_argument("--out", type=Path, default=out, help="the page")
    args = parser.parse_args(argv)
    text = page()
    if not args.check:
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
        return 0
    if not args.out.is_file() or args.out.read_text(encoding="utf-8") != text:
        script = Path(inspect.getfile(page)).name
        print(
            f"{args.out} is not what {holds} gives: run python3 scripts/{script}",
            file=sys.stderr,
        )
        return 1
    print(f"{args.out}: {len(text.splitlines())} lines; up to date")
    return 0

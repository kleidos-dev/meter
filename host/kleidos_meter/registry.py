def budget_problems(event: dict[str, Any]) -> list[str]:
    """Recompute an accepted calibration's arithmetic.

    :param event: The calibration's event.
    :returns: One message per disagreement.
    """
    where = f"event {event.get('id')}"
    problems = []
    for name, rng in event.get("ranges", {}).items():
        points = rng["points_nohm"]
        mean = sum(points) / len(points)
        if abs(round(mean) - rng["mean_nohm"]) > ROUNDING:
            problems.append(f"{where}: range {name} mean is {round(mean)}, not {rng['mean_nohm']}")
        if len(points) > 1:
            sd = math.sqrt(sum((p - mean) ** 2 for p in points) / (len(points) - 1))
            sd_ppm = round(sd / mean * 1e6)
            if abs(sd_ppm - rng["sd_ppm"]) > ROUNDING:
                problems.append(f"{where}: range {name} sd is {sd_ppm} ppm, not {rng['sd_ppm']}")
    means = [event["ranges"][r]["mean_nohm"] for r in ("0", "1") if r in event.get("ranges", {})]
    if len(means) == 2:
        split = round(_ppm_apart(means[0], means[1]))
        if abs(split - event["range_split_ppm"]) > ROUNDING:
            problems.append(
                f"{where}: the range split is {split} ppm, not {event['range_split_ppm']}"
            )
        low, high = min(means), max(means)
        for name, rng in event["ranges"].items():
            if not low - 1000 <= rng["applied_nohm"] <= high + 1000:
                problems.append(
                    f"{where}: range {name} applies a value outside the two range means"
                )
    squares = 0
    for term in event.get("budget", []):
        u = round(term["limit_ppm"] / DIVISORS[term["distribution"]])
        if abs(u - term["u_ppm"]) > ROUNDING:
            problems.append(f"{where}: term {term['term']} is {u} ppm, not {term['u_ppm']}")
        squares += term["u_ppm"] ** 2
    u_c = round(math.sqrt(squares))
    if abs(u_c - event["u_c_ppm"]) > ROUNDING:
        problems.append(f"{where}: u_c is {u_c} ppm, not {event['u_c_ppm']}")
    expanded = round(event["coverage_k"] * event["u_c_ppm"])
    if abs(expanded - event["expanded_ppm"]) > ROUNDING:
        problems.append(f"{where}: U is {expanded} ppm, not {event['expanded_ppm']}")
    for name, rng in event.get("ranges", {}).items():
        if rng["u_ppm"] != event["u_c_ppm"] and not rng.get("u_ppm_own"):
            problems.append(f"{where}: range {name} u_ppm differs from u_c with no reason given")
    return problems


def window_problems(event: dict[str, Any], configuration: dict[str, Any]) -> list[str]:
    """An accepted calibration against its configuration's limits.

    :param event: The calibration's event.
    :param configuration: The configuration's file.
    :returns: One message per limit passed.
    """
    where = f"event {event.get('id')}"
    shunt = configuration["sense"]["shunt"]
    nominal = shunt["nominal_nohm"]
    limit = shunt["tolerance_ppm"] if shunt.get("tolerance_ppm") else shunt["plausible_ppm"]
    problems = []
    for name, rng in event.get("ranges", {}).items():
        deviation = abs(rng["mean_nohm"] - nominal) * 1e6 / nominal
        if deviation > limit:
            problems.append(
                f"{where}: range {name} is {deviation:.0f} ppm from nominal, past {limit} ppm"
            )
    split_max = configuration["expected"]["range_split_max_ppm"]
    if event.get("range_split_ppm", 0) > split_max:
        problems.append(
            f"{where}: the range split {event['range_split_ppm']} ppm is past {split_max}"
        )
    return problems


def normalized_error(first: dict[str, Any], second: dict[str, Any], range_name: str) -> float:
    """``E = |R_2 − R_1| / √(U_1² + U_2²)`` between two calibrations, on one range.

    :param first: The earlier calibration's event.
    :param second: The later one's.
    :param range_name: ``"0"`` or ``"1"``.
    :returns: The figure: above 1, the two do not agree within their uncertainties.
    """
    r1 = first["ranges"][range_name]["applied_nohm"]
    r2 = second["ranges"][range_name]["applied_nohm"]
    u1 = first["expanded_ppm"] * r1 / 1e6
    u2 = second["expanded_ppm"] * r2 / 1e6
    return float(abs(r2 - r1) / math.sqrt(u1**2 + u2**2))


def _sha256(text: str | None) -> str | None:
    return None if text is None else hashlib.sha256(text.encode("utf-8")).hexdigest()


def check(registry: Registry) -> tuple[list[str], list[str]]:
    """Every check of the registry over its files alone: schemas, arithmetic, coherence.

    :param registry: The registry.
    :returns: ``(problems, flags)``: a problem fails the check; a flag is
        reported and does not (an instrument that sits apart from its group).
    """
    problems = list(registry.load_errors)
    flags: list[str] = []
    for kind, items in (
        ("configuration", registry.configurations),
        ("instrument", registry.instruments),
    ):
        schema = registry.schemas.get(kind)
        if schema is None:
            continue
        for name, value in items.items():
            problems += [f"{kind}s/{name}.json: {m}" for m in validate(value, schema)]
    if problems:
        return problems, flags  # the rest reads fields the schemas promise
    for name, configuration in registry.configurations.items():
        if configuration["id"] != name:
            problems.append(f"configurations/{name}.json: its id is {configuration['id']!r}")
    for serial, instrument in registry.instruments.items():
        where = f"instruments/{serial}.json"
        if instrument["serial"] != serial:
            problems.append(f"{where}: its serial is {instrument['serial']!r}")
        ids = [e["id"] for e in instrument["events"]]
        if len(set(ids)) != len(ids):
            problems.append(f"{where}: an event id appears twice")
        if ids != sorted(ids):
            problems.append(f"{where}: the events are not in the order they happened")
        for event in instrument["events"]:
            configuration_id = event.get("configuration")
            if configuration_id and configuration_id not in registry.configurations:
                problems.append(f"{where}: event {event['id']} names no known configuration")
                continue
            for key in ("record", "raw_log"):
                if key in event:
                    text = registry.read(event[key]["path"])
                    if text is None:
                        problems.append(
                            f"{where}: event {event['id']}: {event[key]['path']} is missing"
                        )
                    elif _sha256(text) != event[key]["sha256"]:
                        problems.append(
                            f"{where}: event {event['id']}: {event[key]['path']} changed "
                            "since it was filed"
                        )
            if event["kind"] == "calibration" and event["verdict"] == "accepted":
                in_force = registry.configuration_at(instrument, event["id"])
                if in_force != configuration_id:
                    problems.append(
                        f"{where}: event {event['id']} names {configuration_id}, but the "
                        f"instrument was {in_force} on that day"
                    )
                problems += [f"{where}: {p}" for p in budget_problems(event)]
                problems += [
                    f"{where}: {p}"
                    for p in window_problems(event, registry.configurations[configuration_id])
                ]
        calibrations = accepted_calibrations(instrument)
        voids = _voiding_ids(instrument)
        for earlier, later in zip(calibrations, calibrations[1:], strict=False):
            voided = any(earlier["id"] < void < later["id"] for void in voids)
            if voided:
                continue
            for range_name in ("0", "1"):
                e = normalized_error(earlier, later, range_name)
                if e > 1 and not later.get("acknowledged"):
                    problems.append(
                        f"{where}: event {later['id']} moved range {range_name} by more than "
                        f"the two calibrations explain (E = {e:.2f}); file an 'acknowledged' note"
                    )
    for group in sense_groups(registry).values():
        flags += group["flags"]
    return problems, flags


def sense_core(configuration: dict[str, Any]) -> str:
    """The pair that sets the measurement: the breakout and the shunt.

    :param configuration: The configuration's file.
    :returns: Their two ids, joined.
    """
    sense = configuration["sense"]
    return f"{sense['breakout']['id']}+{sense['shunt']['id']}"


def sense_groups(registry: Registry) -> dict[str, dict[str, Any]]:
    """Instruments of the same sense core, compared.

    Two shunts of one part may differ by its tolerance, so the test is
    membership, not agreement: from three instruments on, one further than
    three scaled median absolute deviations from the median is flagged. The
    scale is never taken below the largest expanded uncertainty among the
    members: instruments that agree to within their own calibrations are not
    apart, and a group where most members share one value (a MAD of zero)
    still flags the one that does not. The group's mean offset from nominal is
    reported whatever the count.

    :param registry: The registry.
    :returns: Each group's ``instruments``, ``mean_offset_ppm``, ``compared`` and
        ``flags``, by its core and range.
    """
    latest: dict[str, list[tuple[str, int, int, int]]] = {}
    for serial, instrument in registry.instruments.items():
        calibrations = accepted_calibrations(instrument)
        if not calibrations:
            continue
        last = calibrations[-1]
        configuration = registry.configurations.get(last["configuration"])
        if configuration is None:
            continue
        nominal = configuration["sense"]["shunt"]["nominal_nohm"]
        for range_name, rng in last["ranges"].items():
            key = f"{sense_core(configuration)} range {range_name}"
            latest.setdefault(key, []).append(
                (serial, rng["applied_nohm"], nominal, last["expanded_ppm"])
            )
    groups = {}
    for key, members in sorted(latest.items()):
        offsets = sorted((value - nominal) * 1e6 / nominal for _, value, nominal, _ in members)
        mean_offset = sum(offsets) / len(offsets)
        flags = []
        if len(members) >= 3:
            median = (
                offsets[len(offsets) // 2]
                if len(offsets) % 2
                else (offsets[len(offsets) // 2 - 1] + offsets[len(offsets) // 2]) / 2
            )
            mad = sorted(abs(o - median) for o in offsets)
            scaled = 1.4826 * (
                mad[len(mad) // 2]
                if len(mad) % 2
                else (mad[len(mad) // 2 - 1] + mad[len(mad) // 2]) / 2
            )
            scaled = max(scaled, *(expanded for _, _, _, expanded in members))
            for serial, value, nominal, _ in members:
                offset = (value - nominal) * 1e6 / nominal
                if abs(offset - median) > 3 * scaled:
                    flags.append(f"{serial} sits apart from the other instruments of {key}")
        groups[key] = {
            "instruments": sorted(serial for serial, _, _, _ in members),
            "mean_offset_ppm": round(mean_offset),
            "compared": len(members) >= 3,
            "flags": flags,
        }
    return groups



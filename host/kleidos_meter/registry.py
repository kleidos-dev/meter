"""The calibration registry: the instrument's calibration, kept in this repository.

The registry under ``calibration/`` is the calibration; the instrument's NVS is
a working copy of it, which a full flash erase loses (``calibration/README.md``).
This module reads the registry, checks it (schemas, arithmetic, coherence),
builds the one file other tools read (``calibration/index.json``), picks the
calibration that holds on a date, and compares an instrument's working copy
with it.

Layout::

    calibration/schemas/*.schema.json         the three file formats
    calibration/configurations/<id>.json      a bill of the parts that set the measurement
    calibration/instruments/<serial>.json     one instrument: its configuration and its events
    calibration/records/...                   the Markdown record and raw log of each event
    calibration/index.json                    generated by scripts/check_calibration_registry.py

Resistances are integers in nano-ohms, relative terms integers in ppm, as on
the wire. Nothing here talks to an instrument; ``calibration_cli`` does.
"""


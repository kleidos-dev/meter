#: The divisor that turns a limit into a standard uncertainty, per distribution
#: (GUM 4.3.7: a rectangular limit a is a/√3; a normal or measured figure is
#: already one standard deviation).
DIVISORS = {"rectangular": math.sqrt(3), "normal": 1.0, "measured": 1.0}

#: How far a typed figure may sit from the one recomputed from its parts: the
#: rounding to an integer ppm or nano-ohm that each of them went through.
ROUNDING = 1

#: Days before a calibration's end that ``verify`` warns.
EXPIRY_WARNING_DAYS = 30


# --- a JSON Schema subset ---------------------------------------------------

_TYPES: dict[str, Callable[[Any], bool]] = {
    "object": lambda v: isinstance(v, dict),
    "array": lambda v: isinstance(v, list),
    "string": lambda v: isinstance(v, str),
    "integer": lambda v: isinstance(v, int) and not isinstance(v, bool),
    "number": lambda v: isinstance(v, int | float) and not isinstance(v, bool),
    "boolean": lambda v: isinstance(v, bool),
    "null": lambda v: v is None,
}


def validate(
    instance: Any, schema: dict[str, Any], root: dict[str, Any] | None = None, path: str = "$"
) -> list[str]:
    """Check *instance* against *schema*, the subset of JSON Schema the registry uses.

    The keywords understood: ``$ref`` (to ``#/$defs/...``), ``type``, ``const``,
    ``enum``, ``properties``, ``required``, ``additionalProperties`` (``false``
    or a schema), ``items``, ``minItems``, ``maxItems``, ``minimum``,
    ``maximum``, ``minLength``, ``pattern``, ``oneOf`` and ``allOf``. An unknown
    keyword is an error in the schema, not silence.

    :param instance: The value, as ``json.loads`` returns it.
    :param schema: The schema, or the part of it that applies here.
    :param root: The whole schema a ``$ref`` is read in; *schema* by default.
    :param path: Where *instance* is in the document, for the messages.
    :returns: One message per failure, each naming the path of the value.
    """
    root = schema if root is None else root
    errors: list[str] = []
    known = {
        "$schema",
        "$id",
        "$defs",
        "$comment",
        "title",
        "description",
        "$ref",
        "type",
        "const",
        "enum",
        "properties",
        "required",
        "additionalProperties",
        "items",
        "minItems",
        "maxItems",
        "minimum",
        "maximum",
        "minLength",
        "pattern",
        "oneOf",
        "allOf",
    }
    unknown = set(schema) - known
    if unknown:
        return [f"{path}: the schema uses {sorted(unknown)}, which this validator does not know"]
    if "$ref" in schema:
        target: Any = root
        for part in schema["$ref"].removeprefix("#/").split("/"):
            target = target[part]
        errors += validate(instance, target, root, path)
    if "type" in schema:
        types = schema["type"] if isinstance(schema["type"], list) else [schema["type"]]
        if not any(_TYPES[name](instance) for name in types):
            return errors + [f"{path}: expected {' or '.join(types)}, found {instance!r}"]
    if "const" in schema and instance != schema["const"]:
        errors.append(f"{path}: must be {schema['const']!r}, found {instance!r}")
    if "enum" in schema and instance not in schema["enum"]:
        errors.append(f"{path}: must be one of {schema['enum']}, found {instance!r}")
    if isinstance(instance, dict):
        properties = schema.get("properties", {})
        for name in schema.get("required", []):
            if name not in instance:
                errors.append(f"{path}: missing {name!r}")
        for name, value in instance.items():
            if name in properties:
                errors += validate(value, properties[name], root, f"{path}.{name}")
            elif schema.get("additionalProperties") is False:
                errors.append(f"{path}: {name!r} is not a field of this format")
            elif isinstance(schema.get("additionalProperties"), dict):
                errors += validate(value, schema["additionalProperties"], root, f"{path}.{name}")
    if isinstance(instance, list):
        if "items" in schema:
            for index, value in enumerate(instance):
                errors += validate(value, schema["items"], root, f"{path}[{index}]")
        if len(instance) < schema.get("minItems", 0):
            errors.append(f"{path}: needs at least {schema['minItems']} items")
        if "maxItems" in schema and len(instance) > schema["maxItems"]:
            errors.append(f"{path}: holds at most {schema['maxItems']} items")
    if _TYPES["number"](instance):
        if "minimum" in schema and instance < schema["minimum"]:
            errors.append(f"{path}: below its minimum {schema['minimum']}")
        if "maximum" in schema and instance > schema["maximum"]:
            errors.append(f"{path}: above its maximum {schema['maximum']}")
    if isinstance(instance, str):
        if len(instance) < schema.get("minLength", 0):
            errors.append(f"{path}: shorter than {schema['minLength']}")
        if "pattern" in schema and not re.search(schema["pattern"], instance):
            errors.append(f"{path}: {instance!r} does not match {schema['pattern']}")
    for branch in schema.get("allOf", []):
        errors += validate(instance, branch, root, path)
    if "oneOf" in schema:
        passing = [b for b in schema["oneOf"] if not validate(instance, b, root, path)]
        if len(passing) != 1:
            detail = "none" if not passing else f"{len(passing)}"
            errors.append(f"{path}: must match exactly one of its forms, matches {detail}")
    return errors


# --- the registry -----------------------------------------------------------


def _ppm_apart(first: int, second: int) -> float:
    """How far two resistances are apart, in ppm of their mean."""
    return abs(first - second) * 1e6 / ((first + second) / 2)


def _date(text: str) -> dt.date:
    """The calendar date of an ISO 8601 timestamp or date."""
    return dt.date.fromisoformat(text[:10])


@dataclass
class Registry:
    """The registry's files, read from a directory or from a git revision.

    :param read: Returns the text of a path relative to ``calibration/``, or
        ``None`` when there is no such file.
    :param listing: Returns the file names (not paths) in a directory relative
        to ``calibration/``.
    :ivar schemas: The three file formats, by name.
    :ivar configurations: The configurations, by id.
    :ivar instruments: The instruments, by serial.
    :ivar load_errors: What could not be read.
    """

    read: Callable[[str], str | None]
    listing: Callable[[str], list[str]]
    schemas: dict[str, dict[str, Any]] = field(default_factory=dict[str, Any])
    configurations: dict[str, dict[str, Any]] = field(default_factory=dict[str, Any])
    instruments: dict[str, dict[str, Any]] = field(default_factory=dict[str, Any])
    load_errors: list[str] = field(default_factory=list)

    @classmethod
    def from_directory(cls, root: Path = ROOT) -> Registry:
        """The registry as the working tree holds it.

        :param root: The ``calibration/`` directory.
        :returns: The registry, read; what could not be is in ``load_errors``.
        """

        def read(relative: str) -> str | None:
            path = root / relative
            return path.read_text(encoding="utf-8") if path.is_file() else None

        def listing(relative: str) -> list[str]:
            path = root / relative
            return sorted(p.name for p in path.iterdir() if p.is_file()) if path.is_dir() else []

        registry = cls(read, listing)
        registry.load()
        return registry

    @classmethod
    def from_git(cls, repository: Path, revision: str) -> Registry:
        """The registry as *revision* of *repository* holds it (``git show``).

        :param repository: A clone of this repository.
        :param revision: A commit, a tag or a branch.
        :returns: The registry, read; what could not be is in ``load_errors``.
        """

        def read(relative: str) -> str | None:
            done = subprocess.run(
                ["git", "-C", str(repository), "show", f"{revision}:calibration/{relative}"],
                capture_output=True,
                text=True,
                check=False,
            )
            return done.stdout if done.returncode == 0 else None

        def listing(relative: str) -> list[str]:
            done = subprocess.run(
                [
                    "git",
                    "-C",
                    str(repository),
                    "ls-tree",
                    "--name-only",
                    f"{revision}:calibration/{relative}",
                ],
                capture_output=True,
                text=True,
                check=False,
            )
            return sorted(done.stdout.split()) if done.returncode == 0 else []

        registry = cls(read, listing)
        registry.load()
        return registry

    def _json(self, relative: str) -> dict[str, Any] | None:
        text = self.read(relative)
        if text is None:
            self.load_errors.append(f"{relative}: missing")
            return None
        try:
            value = json.loads(text)
        except json.JSONDecodeError as exc:
            self.load_errors.append(f"{relative}: not JSON ({exc})")
            return None
        if not isinstance(value, dict):
            self.load_errors.append(f"{relative}: not a JSON object")
            return None
        return value

    def load(self) -> None:
        """Read the schemas, the configurations and the instruments."""
        for name in ("configuration", "instrument", "index"):
            schema = self._json(f"schemas/{name}.schema.json")
            if schema is not None:
                self.schemas[name] = schema
        for name in self.listing("configurations"):
            if name.endswith(".json"):
                value = self._json(f"configurations/{name}")
                if value is not None:
                    self.configurations[name.removesuffix(".json")] = value
        for name in self.listing("instruments"):
            if name.endswith(".json"):
                value = self._json(f"instruments/{name}")
                if value is not None:
                    self.instruments[name.removesuffix(".json")] = value

    # -- reading an instrument's history ----------------------------------------

    def configuration_at(self, instrument: dict[str, Any], event_id: str) -> str | None:
        """The configuration *instrument* was in at event *event_id*: its last change before it.

        Event ids sort in the order things happened (``YYYY-MM-DD-NN``), so a
        change filed later on the same day as a calibration is not the
        configuration that calibration was taken in.

        :param instrument: The instrument's file.
        :param event_id: The event.
        :returns: The configuration's id, or None when no change precedes the event.
        """
        current = None
        for event in instrument.get("events", []):
            if event.get("kind") == "hardware_change" and event["id"] < event_id:
                current = event.get("configuration", current)
        return current


def accepted_calibrations(instrument: dict[str, Any]) -> list[dict[str, Any]]:
    """The instrument's accepted calibrations, oldest first.

    :param instrument: The instrument's file.
    :returns: Their events.
    """
    events = [
        e
        for e in instrument.get("events", [])
        if e.get("kind") == "calibration" and e.get("verdict") == "accepted"
    ]
    return sorted(events, key=lambda e: e["taken_at"])


def _voiding_ids(instrument: dict[str, Any]) -> list[str]:
    """The ids of the hardware changes that void the calibrations before them.

    Ids, not dates: a change filed after a calibration on the same day voids
    it, and one filed before it on that day does not.
    """
    return sorted(
        e["id"]
        for e in instrument.get("events", [])
        if e.get("kind") == "hardware_change" and e.get("voids_calibration")
    )


def windows(
    instrument: dict[str, Any], recalibration_days: Callable[[str], int]
) -> list[dict[str, Any]]:
    """Each accepted calibration with the dates it holds between.

    A calibration holds from the day it was taken until the first of: the day
    the next accepted one was taken, a hardware change that voids it, and its
    configuration's recalibration interval. ``valid_until`` is the first day it
    no longer holds.

    :param instrument: The instrument's file.
    :param recalibration_days: The interval of a configuration, by its id.
    :returns: ``event``, ``valid_from`` and ``valid_until`` of each, oldest first.
    """
    calibrations = accepted_calibrations(instrument)
    voids = _voiding_ids(instrument)
    out = []
    for position, event in enumerate(calibrations):
        start = _date(event["taken_at"])
        ends = [start + dt.timedelta(days=recalibration_days(event["configuration"]))]
        if position + 1 < len(calibrations):
            ends.append(_date(calibrations[position + 1]["taken_at"]))
        ends += [_date(void) for void in voids if void > event["id"]]
        out.append({"event": event, "valid_from": start, "valid_until": min(ends)})
    return out



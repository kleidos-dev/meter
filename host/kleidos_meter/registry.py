def image_problem(firmware: dict[str, Any], image: str, version: str) -> tuple[str, str] | None:
    """Whether an instrument's ``image=`` and firmware version fit a configuration.

    *firmware* is a configuration's ``firmware`` object, or the index summary,
    which carries the same three keys: ``image`` and ``min_version``, and
    ``image_aliases``, the other names the same rig's image has had, each from
    its own version (from 0.8.0 the one image ``meter`` drives the Relay 2
    Click that ``meter_relay2`` drove before), and an optional ``max_version``,
    the last version whose image of that name is this configuration's (the
    HW-316 rig's ``meter`` ends at 0.7.0).

    :param firmware: What the configuration asks for.
    :param image: The instrument's ``image=``.
    :param version: Its firmware version.
    :returns: None when the pair fits; ``("image", <the names accepted>)`` when the
        image is none of them, or is one of them past its last version;
        ``("version", <the lowest version>)`` when it is one of them, too old.
    """
    ceiling = firmware.get("max_version")
    accepted = [(firmware["image"], firmware["min_version"], ceiling)] + [
        (alias["image"], alias["min_version"], None) for alias in firmware.get("image_aliases", [])
    ]
    names = " or ".join(name for name, _, _ in accepted)
    matching = [(floor, top) for name, floor, top in accepted if name.lower() == image.lower()]
    if not matching:
        return "image", names
    if all(top is not None and version_tuple(version) > version_tuple(top) for _, top in matching):
        return "image", f"{names} up to {ceiling}"
    if all(version_tuple(version) < version_tuple(floor) for floor, _ in matching):
        return "version", min((floor for floor, _ in matching), key=version_tuple)
    return None


def configuration_summary(configuration: dict[str, Any]) -> dict[str, Any]:
    """What an instrument reports that can be checked against its configuration.

    :param configuration: The configuration's file.
    :returns: Its entry in the index.
    """
    adc = configuration["sense"]["adc"]
    summary = {
        "id": configuration["id"],
        "sense_core": sense_core(configuration),
        "nominal_nohm": configuration["sense"]["shunt"]["nominal_nohm"],
        "image": configuration["firmware"]["image"],
        "min_version": configuration["firmware"]["min_version"],
        "image_aliases": configuration["firmware"].get("image_aliases", []),
        "bypass_part": configuration["routing"]["bypass"]["part"],
        "adc": {"mfg": adc["mfg"], "die": adc["die"]},
        "recalibration_days": configuration["expected"]["recalibration_days"],
    }
    if "max_version" in configuration["firmware"]:
        summary["max_version"] = configuration["firmware"]["max_version"]
    return summary


def build_index(registry: Registry) -> dict[str, Any]:
    """The one file QA reads: each instrument's calibrations, windows resolved.

    :param registry: The registry.
    :returns: The index, as ``calibration/index.json`` holds it.
    """

    def days(configuration_id: str) -> int:
        return int(registry.configurations[configuration_id]["expected"]["recalibration_days"])

    instruments = {}
    for serial, instrument in sorted(registry.instruments.items()):
        today_configuration = None
        for event in instrument["events"]:
            if event["kind"] == "hardware_change":
                today_configuration = event["configuration"]
        calibrations = []
        for window in windows(instrument, days):
            event = window["event"]
            calibrations.append(
                {
                    "event": event["id"],
                    "configuration": event["configuration"],
                    "taken_at": event["taken_at"],
                    "valid_from": window["valid_from"].isoformat(),
                    "valid_until": window["valid_until"].isoformat(),
                    "device": event["device"],
                    "ranges": {
                        name: {"applied_nohm": rng["applied_nohm"], "u_ppm": rng["u_ppm"]}
                        for name, rng in sorted(event["ranges"].items())
                    },
                    "coverage_k": event["coverage_k"],
                    "expanded_ppm": event["expanded_ppm"],
                    "record": event["record"]["path"],
                }
            )
        drift = []
        accepted = accepted_calibrations(instrument)
        for earlier, later in zip(accepted, accepted[1:], strict=False):
            span = (_date(later["taken_at"]) - _date(earlier["taken_at"])).days or 1
            for range_name in ("0", "1"):
                r1 = earlier["ranges"][range_name]["applied_nohm"]
                r2 = later["ranges"][range_name]["applied_nohm"]
                drift.append(
                    {
                        "from": earlier["id"],
                        "to": later["id"],
                        "range": int(range_name),
                        "normalized_error": round(normalized_error(earlier, later, range_name), 3),
                        "ppm_per_year": round((r2 - r1) * 1e6 / r1 * 365 / span),
                    }
                )
        configurations = {
            cid: configuration_summary(registry.configurations[cid])
            for cid in sorted(
                {c["configuration"] for c in calibrations}
                | ({today_configuration} if today_configuration is not None else set())
            )
        }
        instruments[serial] = {
            "label": instrument.get("label", ""),
            "configuration": today_configuration,
            "configurations": configurations,
            "calibrations": calibrations,
            "drift": drift,
        }
    return {
        "schema": SCHEMA_INDEX,
        "instruments": instruments,
        "sense_groups": {
            key: {k: v for k, v in group.items() if k != "flags"}
            for key, group in sense_groups(registry).items()
        },
    }


def dump_index(index: dict[str, Any]) -> str:
    """The index as it is committed: sorted keys, two-space indent, one final newline.

    :param index: The index.
    :returns: Its text.
    """
    return json.dumps(index, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# --- consuming the index ----------------------------------------------------


def select(index: dict[str, Any], serial: str, on: dt.date) -> tuple[str, dict[str, Any] | None]:
    """The calibration that holds for *serial* on *on*.

    :param index: The index.
    :param serial: The instrument's serial.
    :param on: The day.
    :returns: ``(status, entry)``: ``unregistered`` (no such instrument, or no
        accepted calibration), ``expired`` (the newest one ended on or before
        *on*), or ``applied`` with the entry.
    """
    instrument = index.get("instruments", {}).get(serial)
    if not instrument or not instrument["calibrations"]:
        return "unregistered", None
    for entry in reversed(instrument["calibrations"]):
        start = dt.date.fromisoformat(entry["valid_from"])
        end = dt.date.fromisoformat(entry["valid_until"])
        if start <= on < end:
            return "applied", entry
    newest = instrument["calibrations"][-1]
    if on >= dt.date.fromisoformat(newest["valid_until"]):
        return "expired", newest
    return "unregistered", None


@dataclass
class Verdict:
    """What ``verify`` concluded about an instrument and the registry.

    :ivar status: One of :func:`compare`'s statuses.
    :ivar serial: The instrument's serial as the registry files it: the one it
        reports, or the one an alias maps that to.
    :ivar entry: The calibration's entry in the index, when there is one.
    :ivar differences: What differs from the registry, a sentence each.
    :ivar warnings: What to see to, a sentence each.
    :ivar aliased: Whether an alias mapped the serial the instrument reports
        to :attr:`serial` (:func:`~kleidos_meter.identity.load_aliases`).
    """

    status: str
    serial: str
    entry: dict[str, Any] | None = None
    differences: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    aliased: bool = False

    @property
    def ok(self) -> bool:
        """Whether the instrument's working copy is the registry's."""
        return self.status == "applied"


def compare(
    index: dict[str, Any],
    idn: str,
    info: dict[str, str],
    cal: dict[str, str],
    on: dt.date,
    aliases: Mapping[str, str] | None = None,
) -> Verdict:
    """Compare an instrument with the registry.

    Statuses, in the order they are judged: ``unregistered`` (no serial, an
    unknown one, firmware too old to report one), ``configuration_mismatch``
    (the image, the bypass part or the INA228 is not what the registry says
    this instrument is), ``expired``, ``working_copy_lost`` (its calibration at factory
    defaults: ``shunt_measured=0``), ``working_copy_differs``, ``applied``.

    The serial the instrument reports is looked up as *aliases* maps it,
    when it does, and the verdict names the serial the registry files: the
    one it reports is never in it then. An unknown serial no alias maps
    says how to name one.

    :param index: The index.
    :param idn: The instrument's ``*IDN?``.
    :param info: Its ``SYSTem:INFormation?``'s fields.
    :param cal: Its ``CALibration:DATA?``'s fields.
    :param on: The day.
    :param aliases: Each reported serial and the serial the registry files it
        under (:func:`~kleidos_meter.identity.load_aliases`); None for none.
    :returns: The verdict.
    """
    reported = parse_idn(idn)["serial"]
    if not SERIAL_PATTERN.match(reported):
        return Verdict("unregistered", reported, differences=["the instrument reports no serial"])
    serial = (aliases or {}).get(reported, reported)
    aliased = serial != reported
    status, entry = select(index, serial, on)
    if entry is None:
        verdict = Verdict(
            status,
            serial,
            differences=[f"{serial} has no calibration in the registry"],
            aliased=aliased,
        )
        if not aliased and serial not in index.get("instruments", {}):
            verdict.differences.append(
                "no alias maps it: if the registry files this instrument under a placeholder,"
                f" set {ALIAS_VARIABLE}=<its serial>=<the filed serial> in the environment or"
                " in the repository's .env, which git ignores"
            )
        return verdict
    instrument = index["instruments"][serial]
    summary = instrument["configurations"][entry["configuration"]]
    verdict = Verdict(status, serial, entry, aliased=aliased)
    firmware = parse_idn(idn)["firmware"]
    problem = image_problem(summary, info.get("image", "-"), firmware)
    if problem is not None and problem[0] == "image":
        verdict.differences.append(
            f"image={info.get('image', '-')} where the registry says {problem[1]}"
        )
    expected = {
        "bypass_part": summary["bypass_part"],
        "mfg": summary["adc"]["mfg"],
        "die": summary["adc"]["die"],
    }
    for key, value in expected.items():
        if info.get(key, "").lower() != value.lower():
            verdict.differences.append(
                f"{key}={info.get(key, '-')} where the registry says {value}"
            )
    if problem is not None and problem[0] == "version":
        verdict.differences.append(f"firmware {firmware} is older than {problem[1]}")
    if verdict.differences:
        verdict.status = "configuration_mismatch"
        return verdict
    if status == "expired":
        return verdict
    end = dt.date.fromisoformat(entry["valid_until"])
    if (end - on).days <= EXPIRY_WARNING_DAYS:
        verdict.warnings.append(f"the calibration ends on {end.isoformat()}: recalibrate")
    if cal.get("shunt_measured") != "1":
        verdict.status = "working_copy_lost"
        verdict.differences.append(
            "the instrument holds no measured shunt (its calibration at the defaults)"
        )
        return verdict
    device = entry["device"]
    found = {
        "shunt_uohm_r0": cal.get("shunt_uohm_r0", cal.get("shunt_uohm")),
        "shunt_uohm_r1": cal.get("shunt_uohm_r1", cal.get("shunt_uohm")),
        "cal_tag": cal.get("cal_tag"),
        "cal_date": cal.get("cal_date", "-"),
        "vbus_side": cal.get("vbus_side"),
    }
    for key, value in found.items():
        if str(device[key]) != str(value):
            verdict.differences.append(f"{key}={value} where the registry says {device[key]}")
    if verdict.differences:
        verdict.status = "working_copy_differs"
    return verdict


def restore_messages(entry: dict[str, Any]) -> list[str]:
    """The program messages that write *entry*'s working copy to an instrument.

    The common value first (it clears any per-range one), then range 1's own
    when it differs; the tag, the date and the VBUS side. Never a null: nulls
    are session state.

    :param entry: The calibration's entry in the index.
    :returns: The messages, in order.
    """
    device = entry["device"]
    r0, r1 = device["shunt_uohm_r0"], device["shunt_uohm_r1"]
    messages = [f"SENS:CURR:SHUN {r0 / 1e6:.6f}"]
    if r1 != r0:
        messages.append(f"SENS:CURR:SHUN:RANG1 {r1 / 1e6:.6f}")
    messages.append(f'CAL:TAG "{device["cal_tag"]}"')
    year, month, day = (int(part) for part in device["cal_date"].split("-"))
    messages.append(f"CAL:DATE {year},{month},{day}")
    messages.append("CAL:VBUS SOUR" if device["vbus_side"] == "source" else "CAL:VBUS UNKN")
    return messages


def scale(entry: dict[str, Any], range_index: int, device_shunt_uohm: int) -> float:
    """The factor that rescales a current computed with the device's shunt to the registry's.

    ``I = I_device × (device shunt) / applied`` is exact, because the device
    computes ``I = V / R`` with the copy the capture header repeats.

    :param entry: The calibration's entry in the index.
    :param range_index: 0 or 1.
    :param device_shunt_uohm: The shunt the capture's header names, micro-ohms.
    :returns: The factor.
    """
    applied = entry["ranges"][str(range_index)]["applied_nohm"]
    return float(device_shunt_uohm * 1000 / applied)


def file_digest(text: str) -> str:
    """The ``sha256`` an event records for a filed text.

    :param text: The text.
    :returns: Its digest, hexadecimal.
    """
    return _sha256(text) or ""


def iter_problems(problems: Iterable[str]) -> str:
    """The problems, one per line.

    :param problems: The messages.
    :returns: A text of them.
    """
    return "\n".join(f"  - {p}" for p in problems)

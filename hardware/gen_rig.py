def title_block_lines() -> list[tuple[str, str]]:
    return (
        [("comments", COMPANY)]
        + [("comments", c) for c in COMMENTS + CAL_COMMENTS]
        + [
            ("title", TITLE),
            ("title", CAL_TITLE),
            ("file", "rig.kicad_sch"),
            ("file", CAL_FILE),
            ("license", LICENSE),
            ("source", SOURCE_URL),
        ]
    )


def schematic(
    uuid: str, title: str, comments: list[str], lib: set[str], body: list[Any], root: bool
) -> list[Any]:
    doc = [
        Sym("kicad_sch"),
        [Sym("version"), 20250114],
        [Sym("generator"), "kleidos_meter"],
        [Sym("generator_version"), "1.0"],
        [Sym("uuid"), uuid],
        [Sym("paper"), PAPER],
        [
            Sym("title_block"),
            [Sym("title"), title],
            [Sym("date"), DATE],
            [Sym("rev"), REVISIONS[-1][0]],
            [Sym("company"), COMPANY],
            *([Sym("comment"), i + 1, c] for i, c in enumerate(comments)),
        ],
        [Sym("lib_symbols"), *(LIBRARY[name] for name in sorted(lib))],
        *body,
    ]
    if root:
        doc.append([Sym("sheet_instances"), [Sym("path"), "/", [Sym("page"), "1"]]])
    return doc + [[Sym("embedded_fonts"), Sym("no")]]



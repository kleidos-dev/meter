def ref(name: str) -> str:
    """A part's reference on the sheet being drawn: sheet 1's, or on the calibration sheet the same number plus 100.

    Sheet 2 draws sheet 1's parts again; KiCad's annotation wants every
    reference once in the project, so U1 is U101 there, R100 is R200.
    """
    if not SHEET["key"]:
        return name
    found = re.fullmatch(r"([A-Z]+)(\d+)", name)
    if found is None:
        raise ValueError(f"not a reference: {name!r}")
    prefix, number = found.groups()
    return f"{prefix}{int(number) + 100}"



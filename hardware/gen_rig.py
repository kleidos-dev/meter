"""Generate the bench rig's normative schematic as a KiCad project.

Run it from anywhere; it writes, beside itself, ``rig.kicad_sch`` (sheet 1,
the rig as wired) and ``rig-calibration.kicad_sch`` (sheet 2, the same parts
rewired for the shunt's calibration), the project file ``rig.kicad_pro``, the
symbol library ``rig.kicad_sym`` and the ``sym-lib-table`` that names it. Edit this script rather than the schematic:
the files it emits are generated and a hand edit would be lost on the next run.

    python3 hardware/gen_rig.py
    python3 hardware/export_rig.py      # ERC, the netlist check, rig.pdf and rig.svg

The drawing follows the Kleidos KiCad style (the kit in ``hardware/kicad/``,
copied from the brand repository, with its rules in brand's
``kicad/README.md``): every number below that the style fixes (the grid, the
pins, the stub, the text sizes, the one line width) is read from the kit's
``style.json``; the project file names the kit's drawing sheet and the text
variables its title block prints. The parts are drawn with this project's own
symbols, by the boards' rules: a box with its pins on a 2.54 mm pitch, 2.54 mm
long, names inside; the passives, the ground and the flag as the boards draw
them; no KiCad library is read. Where the wire is the point (the current path,
the Kelvin sense, the leads a relay opens) the drawing connects by wire; where
a net only has to reach another block it connects by a global label of the
net's name. A remark is text and never a label.

The generator is deterministic: run twice, it writes the same bytes.
"""


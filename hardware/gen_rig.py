def box_fields(
    x: float, y: float, lib: str, above: bool = True
) -> tuple[tuple[Any, ...], tuple[Any, ...]]:
    """A box's reference and value, left-justified above its body's left edge."""
    body = next(
        g
        for unit in LIBRARY[lib]
        if isinstance(unit, list) and unit[:1] == [Sym("symbol")] and unit[1].endswith("_0_1")
        for g in unit[2:]
        if isinstance(g, list) and g[:1] == [Sym("rectangle")]
    )
    half, top = -float(body[1][1]), float(body[1][2])
    return (x - half, y - top - 3.81, "left"), (x - half, y - top - 1.27, "left")


def r_fields(x: float, y: float, angle: int) -> tuple[tuple[Any, ...], tuple[Any, ...]]:
    if angle == 90:  # lying down: the reference above, the value below
        return (x, y - 2.54, None), (x, y + 3.81, None)
    return (x + 2.54, y - 1.27, "left"), (x + 2.54, y + 1.27, "left")



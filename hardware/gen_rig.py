# --- S-expressions ---------------------------------------------------------------


class Sym(str):
    """A bare word of the file (a keyword, an enum), written without quotes."""


def check(condition: bool, detail: object) -> None:
    """Refuse to write a sheet that breaks one of the drawing's own rules (*detail* says which)."""
    if not condition:
        raise ValueError(f"the drawing breaks its own rule: {detail!r}")


def fmt(value: float) -> str:
    value = round(value, 4)
    text = f"{0.0 if abs(value) < 1e-9 else value:.4f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def dump(node: object, indent: int = 0) -> str:
    """Serialize *node* in KiCad's layout: a list of atoms on one line, a list with lists one child per line."""
    if isinstance(node, Sym):
        return str(node)
    if isinstance(node, str):
        return '"' + node.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(node, int | float):
        return fmt(node)
    if not isinstance(node, list):
        raise TypeError(f"not a node of the tree: {node!r}")
    head = [dump(x) for x in node if not isinstance(x, list)]
    kids = [x for x in node if isinstance(x, list)]
    if not kids:
        return "(" + " ".join(head) + ")"
    pad = "\t" * (indent + 1)
    return (
        "("
        + " ".join(head)
        + "".join("\n" + pad + dump(k, indent + 1) for k in kids)
        + "\n"
        + "\t" * indent
        + ")"
    )


#: The sheet being drawn: its items, the symbols it uses, its instance path, the key its UUIDs are made from.
SHEET = {"key": "", "path": f"/{ROOT}"}


def uid(*key: object) -> str:
    """A UUID derived from *key*, and from the sheet being drawn when it is not the root."""
    key = (SHEET["key"], *key) if SHEET["key"] else key
    digest = hashlib.sha1("/".join(map(str, key)).encode(), usedforsecurity=False).hexdigest()
    return f"{digest[:8]}-{digest[8:12]}-4{digest[13:16]}-8{digest[17:20]}-{digest[20:32]}"


def at(x: float, y: float, angle: float | None = None) -> list[Any]:
    return [Sym("at"), x, y] + ([] if angle is None else [angle])


def effects(
    size: float = FONT,
    justify: str | None = None,
    hide: bool = False,
    bold: bool = False,
    color: tuple[float, float, float] | None = None,
) -> list[Any]:
    font = [Sym("font"), [Sym("size"), size, size]]
    if bold:
        font.append([Sym("bold"), Sym("yes")])
    if color:
        font.append([Sym("color"), *color, 1])
    out = [Sym("effects"), font]
    if justify:
        out.append([Sym("justify"), *(Sym(word) for word in justify.split())])
    if hide:
        out.append([Sym("hide"), Sym("yes")])
    return out


def stroke(
    width: float = 0.0, kind: str = "default", color: tuple[float, float, float] | None = None
) -> list[Any]:
    out = [Sym("stroke"), [Sym("width"), width], [Sym("type"), Sym(kind)]]
    if color:
        out.append([Sym("color"), *color, 1])
    return out


def fill(kind: str = "none") -> list[Any]:
    return [Sym("fill"), [Sym("type"), Sym(kind)]]


def snapped(value: float) -> bool:
    return bool(abs(value / GRID - round(value / GRID)) < 1e-6)


# --- the library: this project's own symbols ---------------------------------------


def g_line(*points: tuple[float, float], width: float = 0.0) -> list[Any]:
    return [
        Sym("polyline"),
        [Sym("pts"), *([Sym("xy"), x, y] for x, y in points)],
        stroke(width),
        fill(),
    ]


def g_rect(
    x0: float, y0: float, x1: float, y1: float, width: float = BODY, kind: str = "background"
) -> list[Any]:
    return [
        Sym("rectangle"),
        [Sym("start"), x0, y0],
        [Sym("end"), x1, y1],
        stroke(width),
        fill(kind),
    ]


def g_circle(cx: float, cy: float, radius: float, width: float = 0.0) -> list[Any]:
    return [Sym("circle"), [Sym("center"), cx, cy], [Sym("radius"), radius], stroke(width), fill()]


def g_text(body: str, x: float, y: float) -> list[Any]:
    return [Sym("text"), body, at(x, y, 0), effects(SMALL)]


def g_pin(
    number: str,
    name: str,
    x: float,
    y: float,
    angle: int,
    length: float = PIN_LEN,
    kind: str = "passive",
    hide: bool = False,
) -> list[Any]:
    node = [Sym("pin"), Sym(kind), Sym("line"), at(x, y, angle), [Sym("length"), length]]
    if hide:
        node.append([Sym("hide"), Sym("yes")])
    return node + [[Sym("name"), name, effects()], [Sym("number"), number, effects()]]


def header(
    name: str, ref: str, value: str, y_ref: float, y_val: float, description: str, flags: list[Any]
) -> list[Any]:
    return [
        Sym("symbol"),
        f"{LIB}:{name}",
        *flags,
        [Sym("exclude_from_sim"), Sym("no")],
        [Sym("in_bom"), Sym("yes")],
        [Sym("on_board"), Sym("yes")],
        [Sym("property"), "Reference", ref, at(0, y_ref, 0), effects()],
        [Sym("property"), "Value", value, at(0, y_val, 0), effects()],
        [Sym("property"), "Footprint", "", at(0, 0, 0), effects(hide=True)],
        [Sym("property"), "Datasheet", "", at(0, 0, 0), effects(hide=True)],
        [Sym("property"), "Description", description, at(0, 0, 0), effects(hide=True)],
    ]


HIDE_BOTH = [
    [Sym("pin_numbers"), [Sym("hide"), Sym("yes")]],
    [Sym("pin_names"), [Sym("offset"), 0], [Sym("hide"), Sym("yes")]],
]


def finish(node: list[Any], name: str, graphics: list[Any], pins: list[Any]) -> list[Any]:
    return node + [
        [Sym("symbol"), f"{name}_0_1", *graphics],
        [Sym("symbol"), f"{name}_1_1", *pins],
        [Sym("embedded_fonts"), Sym("no")],
    ]


def box(
    name: str, ref: str, left: list[tuple[str, str]], right: list[tuple[str, str]], description: str
) -> list[Any]:
    """A part drawn as a box: its pins left and right on the pitch, names inside, the vendor's or the bench's pin numbers hidden."""

    def width(pins: list[tuple[str, str]]) -> float:
        return max([kit.text_width(n, FONT) for _, n in pins] + [0])

    half = max(math.ceil((width(left) + width(right) + 5.0) / 2 / PITCH) * PITCH, 2 * PITCH)
    rows = max(len(left), len(right), 1)
    top = math.floor((rows - 1) / 2) * PITCH
    pins = [g_pin(num, nm, -half - PIN_LEN, top - i * PITCH, 0) for i, (num, nm) in enumerate(left)]
    pins += [
        g_pin(num, nm, half + PIN_LEN, top - i * PITCH, 180) for i, (num, nm) in enumerate(right)
    ]
    y_top, y_bot = top + PITCH, top - (rows - 1) * PITCH - PITCH
    node = header(
        name,
        ref,
        name,
        y_top + GRID,
        y_bot - GRID,
        description,
        [
            [Sym("pin_numbers"), [Sym("hide"), Sym("yes")]],
            [Sym("pin_names"), [Sym("offset"), 0.762]],
        ],
    )
    return finish(node, name, [g_rect(-half, y_top, half, y_bot)], pins)


